"""
Isolated Unit Tests for Excel Formula Injection (CWE-1236) Remediation.

These tests verify that:
1. `sanitize_excel_cell` properly sanitizes formula triggers ('=', '+', '-', '@').
2. Leading whitespace and control characters before formula characters are properly detected.
3. Legitimate text, Marathi / Unicode strings, numbers, dates, booleans, and None are preserved.
4. Excel exports generated by `AppointmentService.export_appointments` render literal text cells
   rather than executable spreadsheet formulas.
5. NO database connection or mutation occurs (completely in-memory / mocked).
"""

from datetime import date, datetime, time
from decimal import Decimal
from io import BytesIO
from unittest.mock import AsyncMock, MagicMock, patch

import openpyxl
import pytest

from app.services.appointment_service import AppointmentService, sanitize_excel_cell


# ==============================================================================
# 1. Pure Unit Tests for sanitize_excel_cell()
# ==============================================================================

class TestSanitizeExcelCell:
    """Direct isolated unit tests for sanitize_excel_cell helper."""

    def test_formula_prefix_equals(self):
        """'=SUM(1,1)' must be prefixed with single quote."""
        assert sanitize_excel_cell("=SUM(1,1)") == "'=SUM(1,1)"

    def test_formula_prefix_plus(self):
        "'+1+1' must be prefixed with single quote."""
        assert sanitize_excel_cell("+1+1") == "'+1+1"

    def test_formula_prefix_minus(self):
        "'-1+1' must be prefixed with single quote."""
        assert sanitize_excel_cell("-1+1") == "'-1+1"

    def test_formula_prefix_at(self):
        "'@SUM(A1:A2)' must be prefixed with single quote."""
        assert sanitize_excel_cell("@SUM(A1:A2)") == "'@SUM(A1:A2)"

    def test_leading_spaces_before_formula_chars(self):
        """Leading whitespace before '=', '+', '-', '@' must be detected and preserved with single quote prefix."""
        assert sanitize_excel_cell("   =SUM(1,1)") == "'   =SUM(1,1)"
        assert sanitize_excel_cell("  +1+1") == "'  +1+1"
        assert sanitize_excel_cell("    -1+1") == "'    -1+1"
        assert sanitize_excel_cell("  @SUM(A1:A2)") == "'  @SUM(A1:A2)"

    def test_leading_control_characters(self):
        """Leading ASCII control characters (tab, CR, LF, etc.) must be detected and neutralized."""
        assert sanitize_excel_cell("\t=SUM(1,1)") == "'\t=SUM(1,1)"
        assert sanitize_excel_cell("\r\n+1+1") == "'\r\n+1+1"
        assert sanitize_excel_cell("\n-1+1") == "'\n-1+1"
        assert sanitize_excel_cell("\x01@SUM(A1:A2)") == "'\x01@SUM(A1:A2)"
        assert sanitize_excel_cell("\x1f=cmd|' /C calc'!A0") == "'\x1f=cmd|' /C calc'!A0"

    def test_normal_text(self):
        """Normal alphanumeric text, spaces, and punctuation must remain unaltered."""
        assert sanitize_excel_cell("John Doe") == "John Doe"
        assert sanitize_excel_cell("APT-2026-001") == "APT-2026-001"
        assert sanitize_excel_cell("Confirmed") == "Confirmed"
        assert sanitize_excel_cell("Follow-up in 2 weeks.") == "Follow-up in 2 weeks."
        assert sanitize_excel_cell("") == ""
        assert sanitize_excel_cell("   ") == "   "

    def test_marathi_and_unicode_text(self):
        """Marathi (Devanagari) and Unicode text must remain untouched and uncorrupted."""
        assert sanitize_excel_cell("डॉ. राहुल देशमुख") == "डॉ. राहुल देशमुख"
        assert sanitize_excel_cell("तपासणी अहवाल") == "तपासणी अहवाल"
        assert sanitize_excel_cell("रुग्ण क्रमांक १२३") == "रुग्ण क्रमांक १२३"
        assert sanitize_excel_cell("अपॉइंटमेंट यशस्वी") == "अपॉइंटमेंट यशस्वी"

    def test_negative_numeric_values_preserved(self):
        """Numeric values (including negative numbers) must remain numbers, NOT strings."""
        assert sanitize_excel_cell(-42) == -42
        assert type(sanitize_excel_cell(-42)) is int

        assert sanitize_excel_cell(-3.14) == -3.14
        assert type(sanitize_excel_cell(-3.14)) is float

        dec = Decimal("-19.99")
        assert sanitize_excel_cell(dec) == dec
        assert isinstance(sanitize_excel_cell(dec), Decimal)

    def test_positive_numeric_values_preserved(self):
        """Positive numbers and zero must remain numbers."""
        assert sanitize_excel_cell(0) == 0
        assert type(sanitize_excel_cell(0)) is int

        assert sanitize_excel_cell(100) == 100
        assert type(sanitize_excel_cell(100)) is int

        assert sanitize_excel_cell(99.95) == 99.95
        assert type(sanitize_excel_cell(99.95)) is float

    def test_none_value_preserved(self):
        """None value must be preserved as None."""
        assert sanitize_excel_cell(None) is None

    def test_booleans_and_dates_preserved(self):
        """Booleans and date/datetime objects must be preserved as-is."""
        assert sanitize_excel_cell(True) is True
        assert type(sanitize_excel_cell(True)) is bool

        assert sanitize_excel_cell(False) is False
        assert type(sanitize_excel_cell(False)) is bool

        d = date(2026, 10, 31)
        assert sanitize_excel_cell(d) == d

        dt = datetime(2026, 10, 31, 10, 30)
        assert sanitize_excel_cell(dt) == dt

        t = time(10, 30)
        assert sanitize_excel_cell(t) == t

    def test_already_escaped_string_not_double_escaped(self):
        """Strings already beginning with single quote must not get another single quote."""
        assert sanitize_excel_cell("'=SUM(1,1)") == "'=SUM(1,1)"
        assert sanitize_excel_cell("'+1+1") == "'+1+1"
        assert sanitize_excel_cell("'-1+1") == "'-1+1"

    def test_appointment_service_staticmethod(self):
        """AppointmentService.sanitize_excel_cell staticmethod works identically."""
        assert AppointmentService.sanitize_excel_cell("=1+1") == "'=1+1"
        assert AppointmentService.sanitize_excel_cell(-100) == -100


