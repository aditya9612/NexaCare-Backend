@pytest.mark.asyncio
async def test_in_memory_excel_export_sanitizes_formula_injection():
    """
    Verify that export_appointments('excel') neutralizes formula injection payloads
    across user-controlled fields without any database connection.
    """
    # Create mock patient
    mock_patient_1 = MagicMock()
    mock_patient_1.patient_code = "-1+1"
    mock_patient_1.first_name = "=cmd|' /C calc'!A0"
    mock_patient_1.last_name = "Attacker"
    mock_patient_1.phone = "+919876543210"

    mock_doctor_1 = MagicMock()
    mock_doctor_1.first_name = "@SUM(A1:A2)"
    mock_doctor_1.last_name = "EvilDoctor"

    mock_dept_1 = MagicMock()
    mock_dept_1.department_name = "+1+1"

    # Appointment 1 with formula injection payloads
    mock_appt_1 = MagicMock()
    mock_appt_1.appointment_number = "=2+2"
    mock_appt_1.appointment_date = date(2026, 10, 31)
    mock_appt_1.appointment_time = time(10, 30)
    mock_appt_1.queue_token = "@TOKEN"
    mock_appt_1.token_number = 1
    mock_appt_1.patient = mock_patient_1
    mock_appt_1.doctor = mock_doctor_1
    mock_appt_1.department = mock_dept_1
    mock_appt_1.appointment_type = "OPD"
    mock_appt_1.booking_source = "staff"
    mock_appt_1.appointment_status = "Confirmed"
    mock_appt_1.queue_status = "Waiting"
    mock_appt_1.admission_status = ""
    mock_appt_1.admission_recommended = False
    mock_appt_1.check_in_time = None
    mock_appt_1.check_out_time = None
    mock_appt_1.notes = "   =HYPERLINK(\"http://evil.com\")"

    # Appointment 2 with Marathi / Unicode and leading control char notes
    mock_patient_2 = MagicMock()
    mock_patient_2.patient_code = "P-1002"
    mock_patient_2.first_name = "राहुल"
    mock_patient_2.last_name = "देशमुख"
    mock_patient_2.phone = "9876543210"

    mock_doctor_2 = MagicMock()
    mock_doctor_2.first_name = "Alice"
    mock_doctor_2.last_name = "Smith"

    mock_dept_2 = MagicMock()
    mock_dept_2.department_name = "Cardiology"

    mock_appt_2 = MagicMock()
    mock_appt_2.appointment_number = "APT-202"
    mock_appt_2.appointment_date = date(2026, 10, 31)
    mock_appt_2.appointment_time = time(11, 0)
    mock_appt_2.queue_token = "T-2"
    mock_appt_2.token_number = 2
    mock_appt_2.patient = mock_patient_2
    mock_appt_2.doctor = mock_doctor_2
    mock_appt_2.department = mock_dept_2
    mock_appt_2.appointment_type = "OPD"
    mock_appt_2.booking_source = "online"
    mock_appt_2.appointment_status = "Completed"
    mock_appt_2.queue_status = "Completed"
    mock_appt_2.admission_status = ""
    mock_appt_2.admission_recommended = False
    mock_appt_2.check_in_time = datetime(2026, 10, 31, 10, 45)
    mock_appt_2.check_out_time = datetime(2026, 10, 31, 11, 15)
    mock_appt_2.notes = "\t-5+5"

    mock_db = AsyncMock()
    service = AppointmentService(mock_db)

    # Mock tenant resolution and repo list_for_export
    service._resolve_and_validate_tenant_id = AsyncMock(return_value=1)
    service.repo.list_for_export = AsyncMock(return_value=[mock_appt_1, mock_appt_2])

    # Mock user
    mock_user = MagicMock()
    mock_user.id = 1
    mock_user.hospital_id = 1
    mock_user.role = MagicMock()
    mock_user.role.name = "hospital_admin"
    mock_user.is_superuser = False

    with patch("app.repositories.hospital_repository.HospitalRepository.get_by_id", new_callable=AsyncMock) as mock_get_hosp:
        mock_hosp = MagicMock()
        mock_hosp.name = "=INJECTED_HOSPITAL"
        mock_hosp.address = "+123 Hospital Street"
        mock_hosp.phone = "1234567890"
        mock_hosp.email = "info@hosp.com"
        mock_hosp.logo_path = None
        mock_hosp.logo = None
        mock_get_hosp.return_value = mock_hosp

        data_bytes, media_type = await service.export_appointments(
            format_type="excel",
            current_user=mock_user,
        )

    assert media_type == "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet"
    assert len(data_bytes) > 0

    # Load workbook and inspect cells
    wb = openpyxl.load_workbook(BytesIO(data_bytes))
    ws = wb.active

    # 1. Hospital name in Row 1: '=INJECTED_HOSPITAL' must be sanitized
    hosp_cell = ws.cell(row=1, column=1)
    assert hosp_cell.value == "'=INJECTED_HOSPITAL"
    assert hosp_cell.data_type == "s"

    # 2. Row 6 (Appointment 1 - Injection Payloads)
    # Col 1: Sr. No. (should be numeric 1)
    c_sr = ws.cell(row=6, column=1)
    assert c_sr.value == 1
    assert c_sr.data_type == "n"

    # Col 2: Appointment Number ('=2+2')
    c_apt = ws.cell(row=6, column=2)
    assert c_apt.value == "'=2+2"
    assert c_apt.data_type == "s"

    # Col 5: Token ('@TOKEN')
    c_tok = ws.cell(row=6, column=5)
    assert c_tok.value == "'@TOKEN"
    assert c_tok.data_type == "s"

    # Col 6: Patient Code ('-1+1')
    c_pcode = ws.cell(row=6, column=6)
    assert c_pcode.value == "'-1+1"
    assert c_pcode.data_type == "s"

    # Col 7: Patient Name ('=cmd|' /C calc'!A0 Attacker')
    c_pname = ws.cell(row=6, column=7)
    assert c_pname.value == "'=cmd|' /C calc'!A0 Attacker"
    assert c_pname.data_type == "s"

    # Col 8: Patient Phone ('+919876543210')
    c_phone = ws.cell(row=6, column=8)
    assert c_phone.value == "'+919876543210"
    assert c_phone.data_type == "s"

    # Col 9: Doctor Name ('Dr. @SUM(A1:A2) EvilDoctor')
    c_doc = ws.cell(row=6, column=9)
    # Starts with 'Dr. ', normal text
    assert c_doc.value == "Dr. @SUM(A1:A2) EvilDoctor"

    # Col 10: Department Name ('+1+1')
    c_dept = ws.cell(row=6, column=10)
    assert c_dept.value == "'+1+1"
    assert c_dept.data_type == "s"

    # Col 18: Notes ('   =HYPERLINK("http://evil.com")')
    c_notes = ws.cell(row=6, column=18)
    assert c_notes.value == "'   =HYPERLINK(\"http://evil.com\")"
    assert c_notes.data_type == "s"

    # 3. Row 7 (Appointment 2 - Marathi / Unicode & Control Char Notes)
    # Col 1: Sr. No. (should be numeric 2)
    c_sr2 = ws.cell(row=7, column=1)
    assert c_sr2.value == 2
    assert c_sr2.data_type == "n"

    # Col 7: Marathi Patient Name ('राहुल देशमुख')
    c_pname2 = ws.cell(row=7, column=7)
    assert c_pname2.value == "राहुल देशमुख"

    # Col 18: Notes with leading tab ('\t-5+5')
    c_notes2 = ws.cell(row=7, column=18)
    assert c_notes2.value == "'\t-5+5"
    assert c_notes2.data_type == "s"

    # CRITICAL: Verify NO cell in the data rows has data_type == 'f' (formula)
    for row in ws.iter_rows(min_row=6, max_row=7):
        for cell in row:
            assert cell.data_type != "f", f"Cell at ({cell.row}, {cell.column}) has formula data_type: {cell.value}"
